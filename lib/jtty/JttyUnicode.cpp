  bool isHighSurrogate (char16_t c) {return c >= 0xD800 && c <= 0xDBFF;}
  bool isLowSurrogate (char16_t c) {return c >= 0xDC00 && c <= 0xDFFF;}

  void appendCodePoint (std::u16string& text, char32_t code)
  {
    if (code < 0x10000) {
      text += static_cast<char16_t> (code);
    } else {
      code -= 0x10000;
      text += static_cast<char16_t> (0xD800 + (code >> 10));
      text += static_cast<char16_t> (0xDC00 + (code & 0x3FF));
    }
  }

  char32_t upperCodePoint (char32_t code)
  {
    auto const run = std::upper_bound (std::begin (upperRuns), std::end (upperRuns), code,
                                       [] (char32_t value, UpperRun const& r) {return value < r.first;});
    if (run == std::begin (upperRuns)) return code;
    auto const& r = *std::prev (run);
    if (code > r.last || (code - r.first) % r.step) return code;
    return static_cast<char32_t> (static_cast<int> (code) + r.delta);
  }
